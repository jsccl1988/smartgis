"""Generate SMARTGIS_BUILD_ID header + out-dir marker for product DLL gates.

Same gn gen / args / git tip → same id across every product_shared_library.
Artifact check and process-start verify refuse mixed images.

Usage (from GN action):
  python build/tools/gen_build_id.py \\
    --out-h <gen>/smartgis/build_id.h \\
    --out-txt <out>/smartgis_build_id.txt \\
    --debug true|false \\
    --repo <repo_root> \\
    [--args-gn <out>/args.gn]
"""

from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path


def _git_short(repo: Path) -> str:
    try:
        out = subprocess.check_output(
            ["git", "-C", str(repo), "rev-parse", "--short=12", "HEAD"],
            stderr=subprocess.DEVNULL,
            text=True,
        )
        tip = out.strip()
        return tip if tip else "nogit"
    except (OSError, subprocess.CalledProcessError):
        return "nogit"


def _args_hash(args_gn: Path | None) -> str:
    if args_gn is None or not args_gn.is_file():
        return "noargs"
    digest = hashlib.sha256(args_gn.read_bytes()).hexdigest()
    return digest[:8]


def _write_if_changed(path: Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_file() and path.read_text(encoding="utf-8") == body:
        return
    path.write_text(body, encoding="utf-8", newline="\n")


def _compute_id(repo: Path, debug: str, args_gn: Path | None) -> str:
    tip = _git_short(repo.resolve())
    ah = _args_hash(args_gn.resolve() if args_gn else None)
    kind = "D" if debug == "true" else "R"
    return f"{tip}-{kind}-{ah}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-h", type=Path, default=None)
    ap.add_argument("--out-txt", type=Path, default=None)
    ap.add_argument("--debug", choices=("true", "false"), required=True)
    ap.add_argument("--repo", type=Path, required=True)
    ap.add_argument("--args-gn", type=Path, default=None)
    ap.add_argument(
        "--print-only",
        action="store_true",
        help="Print build id only (no file writes)",
    )
    ap.add_argument(
        "--print-id",
        action="store_true",
        help="After writing, print build id on stdout (GN exec_script)",
    )
    args = ap.parse_args(argv)

    build_id = _compute_id(args.repo, args.debug, args.args_gn)
    if args.print_only:
        sys.stdout.write(build_id)
        return 0

    if args.out_h is None or args.out_txt is None:
        ap.error("--out-h and --out-txt required unless --print-only")

    marker = f"SMARTGIS_BUILD_ID={build_id}"
    header = (
        "// Copyright (c) 2026 The Mogu Authors.\n"
        "// All rights reserved.\n"
        "// GENERATED by build/tools/gen_build_id.py - do not edit.\n"
        "#ifndef SMARTGIS_BUILD_ID_GENERATED_H_\n"
        "#define SMARTGIS_BUILD_ID_GENERATED_H_\n"
        f'#define SMARTGIS_BUILD_ID "{build_id}"\n'
        f'#define SMARTGIS_BUILD_ID_MARKER "{marker}"\n'
        "#endif  // SMARTGIS_BUILD_ID_GENERATED_H_\n"
    )
    _write_if_changed(args.out_h, header)
    _write_if_changed(args.out_txt, build_id + "\n")
    if args.print_id:
        sys.stdout.write(build_id)
    else:
        print(f"gen_build_id: {build_id}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
