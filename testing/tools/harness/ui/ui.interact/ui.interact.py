# 2D gestures → resize → 3D gestures → resize → 2D gestures.

import glang.plugin as gp

def main():
    gp.select_map_tab(0)
    gp.pump(800)
    gp.window("activate")
    gp.tool("view.pan")
    gp.click("map_client", 400, 360, "left")
    gp.pump(80)
    gp.pan_burst("map_client", count=6, x=240, y=280, dx=40, dy=24, pump_ms=40)
    gp.wheel_burst("map_client", count=3, x=400, y=400, delta=-120, pump_ms=40)
    gp.mark("interact-2d-a-ok")
    gp.window("resize", w=960, h=640)
    gp.pump(400)
    gp.mark("interact-resize-2d-ok")
    gp.window("resize", w=1280, h=800)
    gp.pump(350)
    gp.mark("interact-pre-3d")
    gp.select_map_tab(1)
    gp.mark("interact-3d-tab")
    gp.pump(600)
    gp.mark("interact-3d-pump")
    gp.drag("map_client", 80, 80, 180, 130)
    gp.pump(100)
    gp.drag("map_client", 180, 130, 110, 170)
    gp.pump(100)
    gp.wheel_burst("map_client", count=2, x=200, y=200, delta=-120, pump_ms=40)
    gp.pump(80)
    gp.wheel_burst("map_client", count=2, x=200, y=200, delta=120, pump_ms=40)
    gp.pump(100)
    gp.key(vk="W")
    gp.pump(60)
    gp.key(vk="A")
    gp.pump(60)
    gp.key(vk="S")
    gp.pump(60)
    gp.key(vk="D")
    gp.pump(120)
    gp.mark("interact-3d-gestures")
    gp.export_bmp("ui-showcase-interact-3d.bmp", "scene3d")
    gp.mark("interact-3d-ok")
    gp.window("resize", w=1400, h=880)
    gp.pump(200)
    gp.window("resize", w=1280, h=800)
    gp.pump(250)
    gp.mark("interact-resize-3d-ok")
    gp.mark("interact-3d-to-2d-begin")
    gp.select_map_tab(0)
    gp.pump(500)
    gp.mark("interact-3d-to-2d-tab")
    gp.mark("interact-resize-restore-ok")
    gp.tool("view.pan")
    gp.pump(120)
    gp.pan_burst("map_client", count=3, x=280, y=300, dx=28, dy=16, pump_ms=50)
    gp.wheel_burst("map_client", count=2, x=400, y=400, delta=120, pump_ms=50)
    gp.pump(200)
    gp.mark("interact-2d-b-ok")
    gp.select_map_tab(0)
    gp.fit_extent()
    gp.pump(400)
    gp.mark("interact-combo-ok")
    gp.mark("interact-script-ok")
