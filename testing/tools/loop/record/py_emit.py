"""Emit a smartgis.script Python file from compacted op dicts."""

from __future__ import annotations

import json
from typing import Any


def _py_str(value: object) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def _fmt_points(points: list[tuple[int, int]]) -> str:
    return ", ".join(f"({int(p[0])}, {int(p[1])})" for p in points)


def emit_py(
    ops: list[dict[str, Any]],
    *,
    script_name: str = "recorded",
    title_comment: str = "",
) -> str:
    _ = script_name
    lines: list[str] = [
        "# Copyright (c) 2026 The Mogu Authors.",
        "# All rights reserved.",
    ]
    if title_comment:
        lines.append(f"# {title_comment}")
    else:
        lines.append("# Auto-generated by loop/record/py_recorder (hybrid OS+agent).")
    lines.extend(
        [
            "",
            "import smartgis",
            "",
            "sg = smartgis.script",
            "",
            'sg.window("activate")',
            "sg.pump(200)",
        ]
    )

    for op in ops:
        name = op.get("op")
        if name == "pump":
            lines.append(f"sg.pump({int(op.get('ms', 100))})")
            continue
        if name == "select_map_tab":
            lines.append(f"sg.select_map_tab({int(op.get('index', 0))})")
        elif name == "mark":
            lines.append(f"sg.mark({_py_str(op.get('token', ''))})")
        elif name == "run_command":
            lines.append(f"sg.run_tool({_py_str(op.get('id', ''))})")
        elif name == "window":
            lines.append(f"sg.window({_py_str(op.get('action', 'activate'))})")
        elif name == "click":
            lines.append(
                f"sg.click(\"shell\", {int(op['x'])}, {int(op['y'])}, \"left\")"
            )
        elif name == "rclick":
            lines.append(f"sg.rclick(\"shell\", {int(op['x'])}, {int(op['y'])})")
        elif name == "drag":
            lines.append(
                "sg.drag("
                f"\"shell\", {int(op['x0'])}, {int(op['y0'])}, "
                f"{int(op['x1'])}, {int(op['y1'])})"
            )
        elif name == "path":
            pts = op.get("points") or []
            lines.append(f"sg.path(\"shell\", {_fmt_points(pts)})")
        elif name == "pan_burst":
            lines.append(
                "sg.pan_burst("
                f"\"shell\", count={int(op['count'])}, "
                f"x={int(op['x'])}, y={int(op['y'])}, "
                f"dx={int(op['dx'])}, dy={int(op['dy'])}, "
                f"pump_ms={int(op['pump_ms'])})"
            )
        elif name == "wheel_burst":
            lines.append(
                "sg.wheel_burst("
                f"\"shell\", count={int(op['count'])}, "
                f"x={int(op['x'])}, y={int(op['y'])}, "
                f"delta={int(op['delta'])}, "
                f"pump_ms={int(op['pump_ms'])})"
            )
        elif name == "wheel":
            lines.append(
                f"sg.wheel(\"shell\", {int(op['x'])}, {int(op['y'])}, "
                f"{int(op['delta'])})"
            )
        elif name == "key":
            lines.append(f"sg.key({_py_str(op.get('name', 'ESCAPE'))})")
        else:
            lines.append(f"# skipped {name}")

    lines.append("")
    return "\n".join(lines)
